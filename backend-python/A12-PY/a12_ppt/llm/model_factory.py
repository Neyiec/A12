from functools import lru_cache

from langchain_openai import ChatOpenAI, OpenAIEmbeddings

from ..config import Settings


@lru_cache(maxsize=32)
def create_chat_model(
    model: str,
    api_key: str,
    base_url: str,
    timeout_seconds: float,
    temperature: float,
    reasoning_effort: str = "medium",
) -> ChatOpenAI:
    kwargs = {}
    if "dashscope.aliyuncs.com" in (base_url or "") or model.lower().startswith("qwen"):
        budgets = {"none": 0, "low": 1024, "medium": 4096, "high": 8192}
        budget = budgets.get(reasoning_effort, 4096)
        kwargs["extra_body"] = {
            "enable_thinking": budget > 0,
            **({"thinking_budget": budget} if budget > 0 else {}),
        }
    elif "api.openai.com" in (base_url or "") and reasoning_effort in {"low", "medium", "high"}:
        kwargs["reasoning_effort"] = reasoning_effort
    return ChatOpenAI(
        model=model,
        api_key=api_key,
        base_url=base_url.rstrip("/") if base_url else None,
        timeout=timeout_seconds,
        max_retries=1,
        temperature=temperature,
        **kwargs,
    )


def create_chat_model_from_settings(
    settings: Settings,
    temperature: float = 0.45,
    model: str | None = None,
    reasoning_effort: str | None = None,
) -> ChatOpenAI:
    return create_chat_model(
        model=model or settings.openai_model,
        api_key=settings.openai_api_key,
        base_url=settings.openai_base_url,
        timeout_seconds=settings.request_timeout_seconds,
        temperature=temperature,
        reasoning_effort=reasoning_effort or "medium",
    )


@lru_cache(maxsize=16)
def create_embedding_model(
    model: str,
    api_key: str,
    base_url: str,
    timeout_seconds: float,
    dimensions: int | None = None,
) -> OpenAIEmbeddings:
    kwargs = {
        "model": model,
        "api_key": api_key,
        "base_url": base_url.rstrip("/") if base_url else None,
        "timeout": timeout_seconds,
        # Bailian's OpenAI-compatible embeddings endpoint accepts raw strings,
        # not the token-id arrays generated by LangChain's length-safe path.
        "check_embedding_ctx_length": False,
        # qwen3.7-text-embedding accepts at most 20 input strings per request.
        "chunk_size": 20,
        "max_retries": 1,
    }
    if dimensions:
        kwargs["dimensions"] = dimensions
    return OpenAIEmbeddings(**kwargs)


def create_embedding_model_from_settings(settings: Settings) -> OpenAIEmbeddings:
    return create_embedding_model(
        model=settings.embedding_model,
        api_key=settings.embedding_api_key,
        base_url=settings.embedding_base_url,
        timeout_seconds=settings.request_timeout_seconds,
        dimensions=settings.embedding_dimensions,
    )
